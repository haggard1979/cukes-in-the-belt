package com.github.cukespace.shared;

import java.io.IOException;
import java.io.InputStream;
import java.io.StringWriter;
import java.io.UncheckedIOException;
import java.net.URI;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.Properties;

/**
 * Describes what the client prepared for the container: the feature files
 * (copied into the deployment, keyed by their original URI), the glue classes
 * and the Cucumber properties. Scanning the classpath inside an application
 * server is not reliable (VFS, nested archives, ...), so the client does it.
 */
public final class DeploymentIndex {
    public static final String BASE = "META-INF/cukespace/";
    public static final String INDEX = BASE + "index.properties";
    public static final String FEATURES = BASE + "features/";

    private static final String FEATURE_PREFIX = "feature.";
    private static final String GLUE = "glue";
    private static final String PROPERTY_PREFIX = "property.";

    private final List<FeatureEntry> features;
    private final List<String> glueClasses;
    private final Map<String, String> properties;

    public DeploymentIndex(final List<FeatureEntry> features, final List<String> glueClasses, final Map<String, String> properties) {
        this.features = List.copyOf(features);
        this.glueClasses = List.copyOf(glueClasses);
        this.properties = Map.copyOf(properties);
    }

    public List<FeatureEntry> getFeatures() {
        return features;
    }

    public List<String> getGlueClasses() {
        return glueClasses;
    }

    public Map<String, String> getProperties() {
        return properties;
    }

    /**
     * @param loader the class loader of the deployment
     * @return the index when the test runs inside a deployment prepared by the client
     */
    public static Optional<DeploymentIndex> load(final ClassLoader loader) {
        try (InputStream stream = loader.getResourceAsStream(INDEX)) {
            if (stream == null) {
                return Optional.empty();
            }
            final Properties raw = new Properties();
            raw.load(stream);
            return Optional.of(fromProperties(raw));
        } catch (final IOException e) {
            throw new UncheckedIOException("Can't read " + INDEX, e);
        }
    }

    public String toPropertiesString() {
        final Properties raw = new Properties();
        for (int i = 0; i < features.size(); i++) {
            raw.setProperty(FEATURE_PREFIX + i + ".path", features.get(i).getPath());
            raw.setProperty(FEATURE_PREFIX + i + ".uri", features.get(i).getUri().toString());
        }
        raw.setProperty(GLUE, String.join(",", glueClasses));
        properties.forEach((key, value) -> raw.setProperty(PROPERTY_PREFIX + key, value));
        final StringWriter writer = new StringWriter();
        try {
            raw.store(writer, "Generated by CukeSpace");
        } catch (final IOException e) {
            throw new UncheckedIOException(e);
        }
        return writer.toString();
    }

    private static DeploymentIndex fromProperties(final Properties raw) {
        final List<FeatureEntry> features = new ArrayList<>();
        for (int i = 0; raw.containsKey(FEATURE_PREFIX + i + ".path"); i++) {
            features.add(new FeatureEntry(
                    raw.getProperty(FEATURE_PREFIX + i + ".path"),
                    URI.create(raw.getProperty(FEATURE_PREFIX + i + ".uri"))));
        }
        final List<String> glue = new ArrayList<>();
        Arrays.stream(raw.getProperty(GLUE, "").split(","))
                .map(String::trim)
                .filter(s -> !s.isEmpty())
                .forEach(glue::add);
        final Map<String, String> properties = new LinkedHashMap<>();
        raw.stringPropertyNames().stream()
                .filter(k -> k.startsWith(PROPERTY_PREFIX))
                .sorted()
                .forEach(k -> properties.put(k.substring(PROPERTY_PREFIX.length()), raw.getProperty(k)));
        return new DeploymentIndex(features, glue, properties);
    }

    /**
     * A feature file copied into the deployment.
     */
    public static final class FeatureEntry {
        private final String path;
        private final URI uri;

        public FeatureEntry(final String path, final URI uri) {
            this.path = path;
            this.uri = uri;
        }

        /**
         * @return the class path resource inside the deployment
         */
        public String getPath() {
            return path;
        }

        /**
         * @return the original URI on the client, used in reports and line filters
         */
        public URI getUri() {
            return uri;
        }
    }
}
